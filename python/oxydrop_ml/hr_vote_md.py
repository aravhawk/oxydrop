"""Generate results/ml/HR_VOTE.md from the hr_vote_*.csv files (no number is typed by hand): `python -m oxydrop_ml.hr_vote report --res ../results/ml`."""
from __future__ import annotations

import os

import numpy as np
import pandas as pd

from . import hr_vote as V

DS_TEXT = {'butppg': 'BUT PPG v2.0 (38 people, leave-one-subject-out CNN)', 'mths': 'MTHS (62 people, leave-one-subject-out CNN)', 'butppg+mths': 'BUT PPG + MTHS pooled (100 people)',
           'hoffman': 'Hoffman (6 people, leave-one-person-out CNN; extra, phone camera, pulse-oximeter reference)'}
V_TEXT = {'cnn': 'CNN alone', 'spec': 'spectral harmonic-sum alone', 'acf': 'autocorrelation alone', 'p2_final_rule': 'pre-registered P2 final rule (HYBRID.md)', 'vote': 'vote only (steps 1-2)',
          'vote+harmonic': 'vote + harmonic/subharmonic correction (1-3)', 'vote+harmonic+octave': 'vote + harmonic + octave check (1-4)', 'vote+harmonic+octave+median5': 'full rule: + causal median of 5 (1-5)'}
FULL = 'vote+harmonic+octave+median5'


def pct(x, d=1):
    return 'n/a' if not np.isfinite(x) else f'{100 * x:.{d}f}%'


def f2(x):
    return 'n/a' if not np.isfinite(x) else f'{x:.2f}'


def ci(r, k, fmt):
    if k + '_lo' not in r or not np.isfinite(r[k + '_lo']):
        return fmt(r[k])
    return f'{fmt(r[k])} [{fmt(r[k + "_lo"])}, {fmt(r[k + "_hi"])}]'


def table(rows, header):
    out = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out)


def report(res):
    t = pd.read_csv(os.path.join(res, 'hr_vote_summary.csv'))
    pa = pd.read_csv(os.path.join(res, 'hr_vote_paired.csv'))
    sp = pd.read_csv(os.path.join(res, 'hr_vote_slow_pulse.csv'))
    sb = pd.read_csv(os.path.join(res, 'hr_vote_slow_band.csv')) if os.path.exists(os.path.join(res, 'hr_vote_slow_band.csv')) else None
    ps = pd.read_csv(os.path.join(res, 'hr_vote_per_subject.csv'))
    L = []
    L.append('# OxyDrop heart-rate voting (FEAT-007)\n')
    L.append('*Generated by `python/oxydrop_ml/hr_vote_md.py` from the `results/ml/hr_vote_*.csv` files; do not edit by hand. Research prototype, not a medical device.*\n')
    L.append('Protocol: `python/oxydrop_ml/amendments/AMENDMENT_5_conformal_openox.md` (Part C), the rule below was written down before any result and not tuned. Exploratory: the pre-registered P2 result is the one in `HYBRID.md`. Window = 10 s; reference = the dataset\'s heart-rate reference; "within 5" is the share of windows within 5 bpm; doubling / halving = estimate 1.8-2.2x / 0.45-0.55x the reference. Intervals are 95 % person bootstraps (people resampled, B = 2000). **Clean** windows pass the shipped v2 quality gate (spectral and autocorrelation agree within 15 %, SQI >= 0.30, ACF >= 0.30); **all** is every window.\n')
    L.append('## The rule\n')
    L.append('Three estimates per window: spectral harmonic-sum `s`, autocorrelation `a` (no learned parameter) and the CNN `c` (leave-one-subject-out). (1) Two estimates agree when they differ by at most max(5 bpm, 6 %). (2) If at least two agree, the answer is the mean of the largest agreeing group; ties go to the group that contains `c`. (3) If none agree, every estimate is moved to the octave {x/2, x, 2x} closest to `c` and the vote is repeated; if still nothing agrees the answer is `c`. (4) If the voted value is an octave (2x or 1/2) of `c` and not near `c`, the answer is `c`. (5) Causal median of the last 5 answers of the same recording. Values stay in 40 to 200 bpm. BUT PPG has one window per recording, so step 5 changes nothing there.\n')
    L.append(f'Target stated before any result: MAE < {V.TARGET_MAE:.0f} bpm and doubling rate < {100 * V.TARGET_DOUBLING:.0f}% on clean clips.\n')
    L.append('## Headline: full rule on clean clips\n')
    rows = []
    for ds in ('butppg', 'mths', 'butppg+mths', 'hoffman'):
        r = t[(t.dataset == ds) & (t.variant == FULL) & (t.scope == 'clean')]
        if not len(r):
            continue
        r = r.iloc[0]
        c = t[(t.dataset == ds) & (t.variant == 'cnn') & (t.scope == 'clean')].iloc[0]
        rows.append([DS_TEXT[ds], f'{int(r.n_windows):,} ({pct(r.share_of_windows, 0)} of windows)', ci(r, 'mae', f2), ci(r, 'within5', pct), pct(r.doubling, 2), pct(r.halving, 2), f2(c.mae), 'yes' if r.meets_target else 'no'])
    L.append(table(rows, ['dataset', 'clean windows', 'MAE bpm [CI]', 'within 5 bpm [CI]', 'doubling', 'halving', 'CNN alone MAE', 'MAE < 3 and doubling < 1%']))
    L.append('')
    for scope, title in (('clean', 'Clean clips'), ('all', 'All clips')):
        L.append(f'## {title}: every estimator and every step\n')
        for ds in ('butppg', 'mths', 'butppg+mths', 'hoffman'):
            d = t[(t.dataset == ds) & (t.scope == scope)]
            if not len(d):
                continue
            n0 = d.iloc[0]
            L.append(f'**{DS_TEXT[ds]}**: {int(n0.n_windows):,} windows, {int(n0.n_people)} people.\n')
            rows = []
            for v in V.VARIANTS:
                r = d[d.variant == v]
                if not len(r):
                    continue
                r = r.iloc[0]
                rows.append([V_TEXT[v], pct(r.coverage, 1), ci(r, 'mae', f2), ci(r, 'within5', pct), pct(r.doubling, 2), pct(r.halving, 2), f'{f2(r.subj_mae_mean)} +- {f2(r.subj_mae_sd)}', f'{f2(r.subj_mae_min)} to {f2(r.subj_mae_max)}'])
            L.append(table(rows, ['estimator / step', 'coverage (answers)', 'MAE bpm [CI]', 'within 5 bpm [CI]', 'doubling', 'halving', 'per-subject MAE mean +- SD', 'per-subject MAE min to max']))
            L.append('')
    L.append('## Paired comparison: full rule against the CNN, the spectral estimator and the P2 rule\n')
    rows = []
    for _, r in pa[(pa.metric == 'mae')].iterrows():
        rows.append([DS_TEXT[r.dataset].split(' (')[0], r.scope, V_TEXT[r.baseline], f2(r.rule_value), f2(r.baseline_value), f'{r.better_is_positive_diff:+.2f} [{r.lo:+.2f}, {r.hi:+.2f}]', r.verdict])
    L.append('MAE, difference = baseline minus rule (positive = the rule is better):\n')
    L.append(table(rows, ['dataset', 'scope', 'versus', 'rule MAE', 'baseline MAE', 'difference [95% CI]', 'verdict']))
    L.append('')
    # reading
    L.append('## Reading, computed from the tables\n')
    for ds in ('butppg', 'mths', 'hoffman'):
        r = t[(t.dataset == ds) & (t.variant == FULL) & (t.scope == 'clean')]
        if not len(r):
            continue
        r = r.iloc[0]
        c = t[(t.dataset == ds) & (t.variant == 'cnn') & (t.scope == 'clean')].iloc[0]
        s = t[(t.dataset == ds) & (t.variant == 'spec') & (t.scope == 'clean')].iloc[0]
        p2 = t[(t.dataset == ds) & (t.variant == 'p2_final_rule') & (t.scope == 'clean')]
        pb = pa[(pa.dataset == ds) & (pa.scope == 'clean') & (pa.metric == 'mae') & (pa.baseline == 'cnn')]
        L.append(f'* **{DS_TEXT[ds].split(" (")[0]}, clean clips**: voting MAE {f2(r.mae)} bpm, within 5 bpm {pct(r.within5)}, doubling {pct(r.doubling, 2)}; CNN alone {f2(c.mae)} bpm; spectral alone {f2(s.mae)} bpm' + (f'; P2 final rule {f2(p2.iloc[0].mae)} bpm' if len(p2) else '') + f'. Target (MAE < 3 bpm, doubling < 1 %) {"met" if r.meets_target else "not met"}' + (f'; paired difference to the CNN {pb.iloc[0].better_is_positive_diff:+.2f} bpm [{pb.iloc[0].lo:+.2f}, {pb.iloc[0].hi:+.2f}], {pb.iloc[0].verdict}.' if len(pb) else '.'))
    b = t[(t.dataset == 'butppg') & (t.scope == 'clean')].set_index('variant')
    L.append(f'* Steps on BUT PPG clean clips (MAE bpm): vote {f2(b.loc["vote", "mae"])}, + harmonic correction {f2(b.loc["vote+harmonic", "mae"])}, + octave check {f2(b.loc["vote+harmonic+octave", "mae"])}; the classical estimators are worse than the CNN there ({f2(b.loc["spec", "mae"])} and {f2(b.loc["acf", "mae"])} against {f2(b.loc["cnn", "mae"])}), so a vote that gives them equal weight does not improve on the CNN.')
    h = t[(t.dataset == 'hoffman') & (t.scope == 'clean')].set_index('variant')
    L.append(f'* On the Hoffman phone data the classical estimators are the better ones on clean windows (spectral {f2(h.loc["spec", "mae"])}, autocorrelation {f2(h.loc["acf", "mae"])}, CNN {f2(h.loc["cnn", "mae"])}), and the full rule reaches {f2(h.loc[FULL, "mae"])} bpm. On all windows (clean or not) the rule reaches {f2(t[(t.dataset == "hoffman") & (t.scope == "all") & (t.variant == FULL)].iloc[0].mae)} bpm, {f2(t[(t.dataset == "hoffman") & (t.scope == "all") & (t.variant == "vote+harmonic+octave")].iloc[0].mae)} before the causal median of 5, which costs about 8 s of extra latency; the quality gate matters more than the median.')
    L.append('')
    L.append('## Per-subject spread (full rule)\n')
    sp_mths = pd.read_csv(os.path.join(res, 'hr_vote_subject_spread.csv'))
    rows = []
    for ds in ('butppg', 'mths', 'hoffman'):
        if ds == 'mths':
            d = sp_mths[(sp_mths.variant == FULL) & (sp_mths.scope == 'clean')]
            if len(d):
                r = d.iloc[0]
                rows.append([DS_TEXT[ds].split(' (')[0], int(r.n_subjects), f2(r.mae_mean), f2(r.mae_sd), f2(r.mae_q50), f'{int(r.n_mae_below_3)} of {int(r.n_subjects)}', 'not listed (CC BY-NC-ND: aggregates only)'])
            continue
        d = ps[(ps.dataset == ds) & (ps.variant == FULL) & (ps.scope == 'clean')].sort_values('mae', ascending=False)
        if len(d):
            worst = ', '.join(f'{r.subject} {f2(r.mae)}' for _, r in d.head(3).iterrows())
            rows.append([DS_TEXT[ds].split(' (')[0], len(d), f2(d.mae.mean()), f2(d.mae.std(ddof=1)), f2(d.mae.median()), f'{int((d.mae < 3).sum())} of {len(d)}', worst])
    L.append(table(rows, ['dataset', 'subjects with clean windows', 'mean of per-subject MAE', 'SD', 'median', 'subjects with MAE < 3 bpm', 'worst three (subject, MAE)']))
    L.append('\nPer-subject tables for the CNN, spectral, P2 rule and full rule on BUT PPG (CC BY) and Hoffman (MIT): `hr_vote_per_subject.csv`. MTHS (CC BY-NC-ND, aggregates only) appears as the spread over its subjects in `hr_vote_subject_spread.csv`.\n')
    L.append('## Slow pulse (Hoffman person 4, about 43 to 48 bpm)\n')
    d = sp[(sp.dataset == 'hoffman')]
    rows = [[V_TEXT[r.variant], f2(r.mae), pct(r.within5), pct(r.doubling), f2(r.mean_estimate)] for _, r in d.iterrows()]
    L.append(f'Windows with reference HR below 50 bpm on the Hoffman set (mean reference {f2(d.iloc[0].mean_ref)} bpm, {int(d.iloc[0].n_windows)} windows, {int(d.iloc[0].n_people)} person). The shipped spectral band starts at 0.85 Hz = 51 bpm (`python/oxydrop/hr.py`), below the reference of this person:\n')
    L.append(table(rows, ['estimator', 'MAE bpm', 'within 5 bpm', 'doubling', 'mean estimate']))
    L.append('')
    if sb is not None:
        rows = [[r.estimator, f2(r.mae), pct(r.within5), pct(r.doubling), f2(r.mean_estimate)] for _, r in sb.iterrows()]
        L.append(f'The same person with the spectral and autocorrelation search band widened to 40 bpm (`hr_vote_slow_band.csv`; all {int(sb.iloc[0].n_windows)} windows of this person with t >= 60 s, mean reference {f2(sb.iloc[0].mean_ref)} bpm; the band-51 rows repeat the shipped floor on exactly these windows):\n')
        L.append(table(rows, ['estimator (band floor)', 'MAE bpm', 'within 5 bpm', 'doubling', 'mean estimate']))
        s51, s40 = sb[sb.estimator == 'spec_band51'].iloc[0], sb[sb.estimator == 'spec_band40'].iloc[0]
        v40 = sb[sb.estimator == 'vote+harmonic+octave+median5 (band40)'].iloc[0]
        L.append(f'\nWidening the band to 40 bpm takes the spectral MAE from {f2(s51.mae)} to {f2(s40.mae)} bpm and within-5 from {pct(s51.within5)} to {pct(s40.within5)}. The CNN does not track this person (MAE {f2(sb[sb.estimator == "cnn"].iloc[0].mae)} bpm, mean estimate {f2(sb[sb.estimator == "cnn"].iloc[0].mean_estimate)}), so with the CNN in the vote the full rule only recovers to {f2(v40.mae)} bpm. One person only, and the band floor of the shipped estimator was chosen by cross-fit on BUT PPG; lowering it needs a re-check there before it is shipped.\n')
    L.append('## Limits\n')
    L.append('* One window per BUT PPG recording; MTHS reference HR is per recording (a constant for all its windows). Reference HR on Hoffman comes from a pulse oximeter.\n* The CNN HR on BUT and MTHS comes from the FEAT-006 leave-one-subject-out runs (recipe P). Spectral and autocorrelation estimates have no learned parameter except the shipped quality gate.\n* The rule is fixed and untuned; a vote weighted by estimator quality may do better, which would need its own inner-fold selection.\n* Nothing here is tuned to a phone; other phones are untested.\n')
    L.append('## Reproduce\n')
    L.append('```\nSTAGE=hr-vote bash scripts/reproduce_ml.sh     # inputs need the cache (hr_raw_*.npz, shards); `python -m oxydrop_ml.hr_vote inputs|run|slow|report`\n```\n')
    open(os.path.join(res, 'HR_VOTE.md'), 'w').write('\n'.join(L))
    print('wrote', os.path.join(res, 'HR_VOTE.md'))
